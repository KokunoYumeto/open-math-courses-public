"""Finite exact examples for the auxiliary-function preparations."""
from collections import Counter
from datetime import datetime, timezone
from itertools import combinations, product
from pathlib import Path
import json
import sympy as s

checks = Counter()


def check(test, family):
    assert bool(test), (family, test)
    checks[family] += 1


z, w, eps = s.symbols("z w eps")
# Compare Hermite's inverse-series construction with polynomial division.
# Remainders provide a separate exact interpolation computation.
for nodes in range(2, 6):
    for order in range(1, 5):
        omega = s.prod((z-h)**order for h in range(nodes))
        f = sum(s.Rational((-1)**k*(k+2), k+1)*z**k
                for k in range(nodes*order+4))
        interpolant = 0
        for h in range(nodes):
            oh = s.cancel(omega/(z-h)**order)
            inv = s.series(1/oh.subs(z,h+w),w,0,order).removeO().expand()
            for m in range(order):
                a = s.diff(f,z,m).subs(z,h)/s.factorial(m)
                interpolant += oh*a*sum(inv.coeff(w,j)*(z-h)**(m+j)
                                        for j in range(order-m))
        interpolant = s.expand(interpolant)
        check(s.expand(interpolant-s.rem(f,omega,z)) == 0,
              "Hermite_vs_polynomial_remainder")
        for h,m in product(range(nodes),range(order)):
            check(s.diff(f-interpolant,z,m).subs(z,h) == 0,
                  "all_sampled_jets")

basis = [1-3*z**2+2*z**3,z-2*z**2+z**3,
         3*z**2-2*z**3,-z**2+z**3]
jet_matrix = s.Matrix([[s.diff(b,z,m).subs(z,h) for b in basis]
                       for h,m in [(0,0),(0,1),(1,0),(1,1)]])
check(jet_matrix == s.eye(4),"worked_Hermite_cubic")
check(s.expand(sum(a*b for a,b in zip([eps,eps,2*eps,eps],basis))
               -eps*(1+z)) == 0,"worked_Hermite_cubic")
check((z**2*(z-1)**2).subs(z,2) == 4,"worked_Hermite_cubic")

# Derivatives computed directly in x, compared with matrix-substitution bounds.
x0,x1 = s.symbols("x0 x1")
y0,y1 = s.symbols("y0 y1")
poly = 1+2*y0-3*y1+5*y0*y1+7*y0**2-2*y1**3+4*y0*y1**3
for matrix in [s.Matrix([[1,2],[-1,1]]),
               s.Matrix([[s.Rational(1,2),-1],[2,s.Rational(1,3)]]),
               s.Matrix([[0,3],[0,-2]])]:
    changed = s.expand(poly.subs({y0:matrix[0,0]*x0+matrix[1,0]*x1,
                                 y1:matrix[0,1]*x0+matrix[1,1]*x1},
                                simultaneous=True))
    entry_sum = sum(abs(a) for a in matrix)
    for degree in range(5):
        original_max = max(abs(s.Poly(poly,y0,y1).coeff_monomial(
            y0**a*y1**(degree-a))) for a in range(degree+1))
        for a in range(degree+1):
            jet = s.diff(changed,x0,a,x1,degree-a).subs({x0:0,x1:0})
            jet /= s.factorial(a)*s.factorial(degree-a)
            check(abs(jet) <= entry_sum**degree*original_max,
                  "divided_direction_bound")

# The maximum-minor construction is checked for exact complex matrices.
for small in [s.Matrix([[1,2,0],[0,1,1]]),
              s.Matrix([[1,s.I,2],[2,1,0]])]:
    U = s.Matrix.vstack(small,small[0,:]+2*small[1,:],
                       3*small[0,:]-small[1,:])
    minors = [(abs(U.extract(rows,cols).det()),rows,cols)
              for rows in combinations(range(U.rows),2)
              for cols in combinations(range(U.cols),2)]
    magnitude,rows,cols = max(minors,key=lambda item:float(item[0]))
    pivot = U.extract(rows,cols)
    for j in range(U.rows):
        coefficients = U.extract([j],cols)*pivot.inv()
        check(coefficients*U.extract(rows,range(U.cols)) == U[j,:],
              "maximum_minor_row_reconstruction")
        check(all(abs(c) <= 1 for c in coefficients),
              "maximum_minor_row_bound")

# A field generated by sqrt(2),sqrt(3) has the four selected independent
# monomials; the conjugate matrix detects independence over Q.
field_basis=[1,s.sqrt(2),s.sqrt(3),s.sqrt(6)]
conjugates=s.Matrix([[1,a*s.sqrt(2),b*s.sqrt(3),a*b*s.sqrt(6)]
                     for a,b in product([-1,1],repeat=2)])
check(conjugates.det()!=0,"controlled_field_basis")
check(all(s.simplify(x*x).is_rational for x in field_basis),
      "controlled_field_basis")

result={"utc":datetime.now(timezone.utc).isoformat(),"state":"passed",
        "checks":dict(checks),"total":sum(checks.values()),
        "limits":"Finite exact examples test Hermite interpolation against polynomial division, all specified jets, direction bounds, maximal-minor row reconstruction and a field basis. The general proofs are in the manuscript; these tests do not establish the full elliptic logarithm estimate."}
Path(__file__).with_suffix(".json").write_text(
    json.dumps(result,indent=2)+"\n",encoding="utf-8")
print(json.dumps(result))
