"""Figure 22.20: the certified coefficient reductions and their mechanism."""
from pathlib import Path
import json
import math
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

root=Path(__file__).resolve().parent
d=json.loads((root/'elliptic-integral-points-check.json').read_text())
bounds=[d['initial_coefficient_bound'],28,7,6]
theta=sum(d['theta_interval_numerators'])/(2*d['common_interval_denominator'])
plt.rcParams.update({'font.size':11,'axes.spines.top':False,'axes.spines.right':False})
fig,ax=plt.subplots(1,2,figsize=(11.8,4.8),layout='constrained')
labels=['Initial bound','First lattice','Second lattice','Third lattice']
y=np.arange(4)
ax[0].barh(y,[math.log10(b) for b in bounds],height=.50,color=['#8999ac','#4776a6','#359b8d','#207d68'])
ax[0].set_yticks(y,labels);ax[0].invert_yaxis();ax[0].set_xlim(0,88)
ax[0].set_xlabel('log10 of the coefficient bound')
ax[0].set_title('Exact bounds for |n|')
for j,b in enumerate(bounds):
    text='75-digit integer' if j==0 else str(b)
    ax[0].text(math.log10(b)+1.3,j,text,va='center',fontsize=10)
ax[0].grid(axis='x',alpha=.2)
ns=np.arange(1,7);dist=[abs(n*theta-round(n*theta)) for n in ns]
grid=np.linspace(1,6,250)
ax[1].semilogy(grid,5*np.exp(-7*grid**2/24),color='#4776a6',label='Necessary upper bound')
ax[1].semilogy(ns,dist,'o',color='#be652b',markersize=7,label='Distance of n theta to Z')
ax[1].set_xticks(ns);ax[1].set_xlabel('Coefficient |n|');ax[1].set_ylabel('Normalized logarithmic size')
ax[1].set_title('Integral points must have small logarithms')
ax[1].grid(alpha=.2);ax[1].legend(fontsize=9,loc='lower left')
fig.suptitle('The subgroup generated by (3, 5) on y² = x³ − 2',fontsize=15)
fig.savefig(root/'elliptic-integral-reduction.png',dpi=180)
plt.close(fig)
