"""Finite lattice quotients and exact division-field examples for 22.35--36."""
from collections import Counter
from datetime import datetime, timezone
from itertools import product
from pathlib import Path
import hashlib
import json
import sympy as sp

counts=Counter()
for rank in range(5):
    for b in range(1,7):
        reps=list(product(range(b),repeat=rank))
        assert len(reps)==b**rank and len(set(reps))==len(reps)
        counts['lattice_fibre_cardinality']+=1
        for v in reps:
            shifted=tuple(x+b*(i+1) for i,x in enumerate(v))
            assert tuple(x%b for x in shifted)==v
            counts['lattice_coset_representatives']+=1
x=sp.symbols('x')
for b in range(1,13):
    # Eisenstein at 2 gives the independently known irreducibility criterion;
    # exact factorization checks the stated finite examples as well.
    f=sp.Poly(x**b-2,x,domain=sp.QQ)
    assert f.is_irreducible and f.degree()==b
    assert f.degree()<=b**2
    counts['multiplicative_division_degree']+=1
    f=sp.Poly(x**(2*b)-2,x,domain=sp.QQ)
    assert f.is_irreducible and f.degree()==2*b
    assert f.degree()//2==b  # Q(sqrt(2)) is generated by eta**b.
    counts['absolute_relative_degree_tower']+=1
    assert sp.Rational(1,b)*b==1
    counts['additive_division_degree_one']+=1
f=sp.Poly(x**3-2*x+2,x,domain=sp.QQ)
assert f.is_irreducible and sp.gcd(f,f.diff()).degree()==0
assert f.degree()+1==2**2  # Three y=0 points and the identity on the cubic.
counts['elliptic_two_torsion_field_example']=1

result={'utc':datetime.now(timezone.utc).isoformat(),'state':'passed','cases':dict(counts),
        'total':sum(counts.values()),'script_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'limits':'Finite exact examples, not a test of analytic connectedness or a substitute for the general proofs.'}
Path(__file__).with_suffix('.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
print(json.dumps(result,indent=2))
